export function howToGet(id: string): string | undefined {
  if (EXPLICIT[id]) return EXPLICIT[id];
  if (id.startsWith("stripped_")) return "Use an axe on the matching log, stem, wood, or hyphae.";
  if (id.endsWith("_log") || id.endsWith("_stem")) return "Chop the matching tree or fungus.";
  if (id.endsWith("_ore") || id.startsWith("raw_"))
    return "Mine the matching ore with a suitable pickaxe.";
  if (id.endsWith("_sapling")) return "Break the matching leaves, or find a sapling in a chest.";
  if (id.endsWith("_seeds") || id.endsWith("_beans")) return "Harvest the matching crop.";
  if (id.startsWith("potion_") && id !== "potion_water")
    return "Brew it in a brewing stand. Blaze powder fuels the stand.";
  if (id.startsWith("splash_potion_")) return "Brew gunpowder into the drinkable potion.";
  if (id.startsWith("lingering_potion_")) return "Brew dragon's breath into the splash potion.";
  return undefined;
}
